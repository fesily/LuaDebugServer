#!/usr/bin/env python3
"""Assemble the publish directory's extension surface.

Replaces the old `compile/copy_extension.lua`, which needed bee's Lua bindings:

  * the generated manifest (built from tools/gen_package_json.py) is copied to
    `publish/package.json`,
  * the whole `extension/` tree is copied (js, script, images, package.nls.json),
  * the published `script/` tree is dropped first, so a renamed or removed entry
    script cannot survive as a stale file that the debugger would still load,
  * `LICENSE` and `README.md` are copied next to it.

Only the Python standard library is used; this runs as a CMake custom command.
"""

import argparse
import json
import os
import shutil
import sys

# Generated into the source tree by older builds; the manifest now comes from the
# build directory, so an existing copy must never be published by accident.
MANIFEST_NAME = "package.json"


def copy_tree(source, destination):
    for entry in sorted(os.listdir(source)):
        source_path = os.path.join(source, entry)
        destination_path = os.path.join(destination, entry)
        if os.path.isdir(source_path):
            os.makedirs(destination_path, exist_ok=True)
            copy_tree(source_path, destination_path)
        else:
            shutil.copyfile(source_path, destination_path)
            shutil.copymode(source_path, destination_path)


def remove_legacy_bridges(publish_dir):
    """Drops the pre-unification per-version bridges.

    The bridge is one file per platform/arch (`runtime/<platform>/luadebug.so`)
    now; a `runtime/<platform>/<version>/luadebug.*` left over from an older build
    would be indistinguishable from a shipped artifact.
    """
    runtime_dir = os.path.join(publish_dir, "runtime")
    if not os.path.isdir(runtime_dir):
        return
    for platform in sorted(os.listdir(runtime_dir)):
        platform_dir = os.path.join(runtime_dir, platform)
        if not os.path.isdir(platform_dir):
            continue
        for entry in sorted(os.listdir(platform_dir)):
            version_dir = os.path.join(platform_dir, entry)
            if not os.path.isdir(version_dir):
                continue
            for name in ("luadebug.so", "luadebug.dll"):
                stale = os.path.join(version_dir, name)
                if os.path.exists(stale):
                    print("remove legacy bridge %s" % stale)
                    os.remove(stale)


def remove_stale(publish_dir):
    stale = [
        os.path.join(publish_dir, "script"),
        os.path.join(publish_dir, "bin", "main.lua"),
        # Runtime droppings of an earlier adapter run must never ship (the copy
        # below would otherwise resurrect them from an older publish tree).
        os.path.join(publish_dir, "client.log"),
        os.path.join(publish_dir, "tmp"),
    ]
    for path in stale:
        if os.path.isdir(path):
            shutil.rmtree(path)
        elif os.path.exists(path):
            os.remove(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", required=True)
    parser.add_argument("--publish-dir", required=True)
    parser.add_argument("--manifest", required=True)
    parser.add_argument("--platform", required=True)
    args = parser.parse_args()

    source_root = os.path.abspath(args.source_root)
    publish_dir = os.path.abspath(args.publish_dir)
    manifest = os.path.abspath(args.manifest)
    extension_dir = os.path.join(source_root, "extension")

    with open(manifest, "r", encoding="utf-8") as handle:
        generated = json.load(handle)
    if generated.get("name") != "lua-debug-server":
        print("assemble_extension: %s is not the lua-debug-server manifest" % manifest, file=sys.stderr)
        return 1

    os.makedirs(publish_dir, exist_ok=True)
    remove_stale(publish_dir)
    remove_legacy_bridges(publish_dir)

    copy_tree(extension_dir, publish_dir)

    # The source tree may hold a manifest generated by an older build system; the
    # one written here is the only manifest that may be published.
    published_manifest = os.path.join(publish_dir, MANIFEST_NAME)
    shutil.copyfile(manifest, published_manifest)

    for name in ("LICENSE", "README.md"):
        shutil.copyfile(os.path.join(source_root, name), os.path.join(publish_dir, name))

    print("assemble_extension: %s -> %s (%s)" % (extension_dir, publish_dir, args.platform))
    return 0


if __name__ == "__main__":
    sys.exit(main())
